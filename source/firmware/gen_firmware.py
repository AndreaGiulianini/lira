"""Generates the RMK firmware configuration (keyboard.toml + vial.json) from layout.py and the PCB pin assignment.

    python3 firmware/gen_firmware.py        (after `make pcb`, which writes <build>/pcb/interface.json)
    -> <build>/firmware/keyboard.toml + vial.json, copied into the RMK project firmware/rmk by `make firmware`

The [layout] section comes from rmkit (converted from build/kle-via.json), so the firmware, Vial and the PCB
all use the same matrix positions. The default keymap below follows the Agar mini legends; everything can be
changed live from Vial.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
import layout as L  # noqa: E402

from paths import BUILD  # noqa: E402

RMKIT = str(Path.home() / ".cargo/bin/rmkit")
IFACE = json.loads((BUILD / "pcb/interface.json").read_text())
OUT = BUILD / "firmware"

_ = "_"  # transparent
# One entry per key in layout.KEYS order: numpad rows, then the main block rows.
# Layer 0: what is printed on the Agar keycaps. Right space = Space on tap, layer 1 while held; the right-hand
# modifiers send the arrow printed on them when tapped (↑ ← ↓ →, as on the Agar caps) and act as modifiers
# when held.
BASE = [
    "Kp7", "Kp8", "Kp9", "KpMinus",
    "Kp4", "Kp5", "Kp6", "KpPlus",
    "Kp1", "Kp2", "Kp3", "KpEnter",
    "Kp0", "KpDot",
    "Escape", "Q", "W", "E", "R", "T", "Y", "U", "I", "O", "P", "Backslash", "Backspace",
    "Tab", "A", "S", "D", "F", "G", "H", "J", "K", "L", "Semicolon", "Enter",
    "LShift", "Z", "X", "C", "V", "B", "N", "M", "Comma", "Dot", "MT(Up, RShift, MODTAP)", "LT(2, Right, MODTAP)",
    "LAlt", "LGui", "Space", "LT(1, Space, THUMB)", "MT(Left, RGui, MODTAP)", "MT(Down, RAlt, MODTAP)",
]
# Layer 1 (hold the right space): number row, symbols, F-keys on the numpad, navigation on the arrow keys.
NUMBERS = [
    "F7", "F8", "F9", "KpSlash",
    "F4", "F5", "F6", "KpAsterisk",
    "F1", "F2", "F3", "F12",
    "F10", "F11",
    "Grave", "Kc1", "Kc2", "Kc3", "Kc4", "Kc5", "Kc6", "Kc7", "Kc8", "Kc9", "Kc0", "Minus", "Equal",
    "CapsLock", _, _, _, _, _, "LeftBracket", "RightBracket", _, _, "Quote", _,
    _, _, _, _, _, _, _, _, _, "Slash", "PageUp", "End",
    _, _, _, _, "Home", "PageDown",
]
# Layer 2 (hold fn): Bluetooth profiles (User0-2, hold 5 s to forget the paired host), USB/BLE switch (User6),
# media keys, forward delete, and the bootloader (fn + Esc) to drag a new .uf2 onto the keyboard.
SYSTEM = [
    _, _, _, _,
    _, _, _, _,
    _, _, _, _,
    _, _,
    "Bootloader", "User0", "User1", "User2", "User6", _, _, _, _, _, _, _, "Delete",
    _, _, _, _, _, _, _, _, _, _, _, _,
    _, "AudioMute", "AudioVolDown", "AudioVolUp", "MediaPlayPause", "MediaPrevTrack", "MediaNextTrack", _, _, _,
    _, _,
    _, _, _, _, _, _,
]
LAYERS = [("base", BASE), ("numbers", NUMBERS), ("system", SYSTEM)]


def layout_section():
    out = subprocess.run([RMKIT, "layout", "convert", str(BUILD / "kle-via.json")], capture_output=True,
                         text=True, check=True).stdout
    return out[out.index("[layout]"):].strip()


def keys_string(layer, rows):
    """RMK wants the keys in the [layout] map order (one text line per map line); our lists follow layout.KEYS."""
    by_pos = {(k.row, k.col): layer[i] for i, k in enumerate(L.KEYS)}
    return "\n".join(" ".join(by_pos[rc] for rc in row) for row in rows)


def find_key(label):
    return next(k for k in L.KEYS if k.label == label)


def keyboard_toml():
    for name, layer in LAYERS:
        assert len(layer) == len(L.KEYS), (name, len(layer))
    lay = layout_section()
    rows = [[(int(r), int(c)) for r, c in re.findall(r"\((\d+),(\d+)", line)]
            for line in lay.split('"""')[1].strip().splitlines()]
    m = IFACE["matrix"]
    esc, ret = find_key("esc"), find_key("return")
    q = lambda pins: "[" + ", ".join('"%s"' % p for p in pins) + "]"  # noqa: E731
    layers = "\n".join('''[[keymap.layer]]
name = "%s"
keys = """
%s
"""
''' % (name, keys_string(layer, rows)) for name, layer in LAYERS)
    return '''# Generated by firmware/gen_firmware.py from layout.py and the PCB pin map - do not edit by hand.
[keyboard]
name = "lira"
product_name = "Lira"
manufacturer = "Lira"
vendor_id = 0x4c4b
product_id = 0x0040
chip = "nrf52840"
usb_enable = true

[chip.nrf52840]
# Normal-voltage mode (VDD = VDDH = 3.3 V from the TPS7A0233): REG0 is not used -> OFF.
dcdc_reg0 = false
# REG1 DC/DC ON: the module has its inductors inside (Ebyte E73-2G4M08S1C datasheet p.7, module schematic: L2 10 uH
# + L1 15 nH between DCC and DEC4), as on the nice!nano; it saves a few mA in radio bursts. If a module ever does not
# start with it, the bootloader still does (it sets its own regulator): flash a build with false here.
dcdc_reg1 = true

[matrix]
row_pins = %s
col_pins = %s
# diodes: cathode towards the row (col2row, RMK default)

%s

[keymap]
layers = 4

%s
[behavior.morse.profiles]
# thumb layer-tap: becomes the layer only if another key is pressed and released while it is held
THUMB = { permissive_hold = true, hold_on_other_press = false, hold_timeout = "200ms", gap_timeout = "200ms" }
# arrow/modifier keys: a modifier as soon as another key goes down while held
MODTAP = { permissive_hold = false, hold_on_other_press = true, hold_timeout = "200ms", gap_timeout = "200ms" }

[light]
# red LED on P1.04 (the bootloader's LED): Caps Lock
capslock = { pin = "%s", low_active = false }

[ble]
enabled = true
# battery through a 10M (VBAT side) + 10M (GND side) divider with 10 nF into P0.31 / AIN7 (sampled every 30 s)
battery_adc_pin = "%s"
adc_divider_measured = 10000
adc_divider_total = 20000

[host]
vial_enabled = true
rynk_enabled = false
# hold Esc + Return to unlock Vial's protected functions (matrix tester, bootloader...)
unlock_keys = [[%d, %d], [%d, %d]]

[event]
# subscriber slots of the connection status: the audio switch (src/audio_gate.rs, sound card only in USB mode through
# the load switch on P1.02) is its only listener in this build (RMK adds its own slots for a display, rynk or a split)
connection_status_change.subs = 2
# battery readings: RMK's battery processor and the low-battery cut-off (src/battery_guard.rs)
battery_adc.subs = 2
''' % (q(m["rows"]), q(m["cols"]), lay, layers, m["status_led"], m["battery_adc"],
       esc.row, esc.col, ret.row, ret.col)


def main():
    toml = keyboard_toml()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "keyboard.toml").write_text(toml)
    vial = subprocess.run([RMKIT, "layout", "convert", "--to-vial", str(OUT / "keyboard.toml")],
                          capture_output=True, text=True, check=True).stdout
    data = json.loads(vial[vial.index("{"):])
    data["name"] = "Lira"
    data["vendorId"], data["productId"] = "0x4C4B", "0x0040"
    data["customKeycodes"] = [{"name": "BT%d" % i, "title": "Bluetooth profile %d (hold 5 s: forget host)" % i,
                               "shortName": "BT%d" % i} for i in range(3)] + [
        {"name": "BT_NEXT", "title": "Next Bluetooth profile", "shortName": "BT>"},
        {"name": "BT_PREV", "title": "Previous Bluetooth profile", "shortName": "BT<"},
        {"name": "BT_CLR", "title": "Forget the host of this profile", "shortName": "BTclr"},
        {"name": "USB_BLE", "title": "Switch output USB / Bluetooth", "shortName": "USB/BT"},
    ]
    (OUT / "vial.json").write_text(json.dumps(data, indent=1))
    print("wrote %s/keyboard.toml and vial.json (rows %s, cols %s)" % (
        OUT.relative_to(ROOT), IFACE["matrix"]["rows"], IFACE["matrix"]["cols"]))


if __name__ == "__main__":
    main()
